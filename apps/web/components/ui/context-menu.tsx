// Matches the distance Radix Select uses to tell a press-drag-release from a click.
const RELEASE_SELECT_MIN_TRAVEL_PX = 10;

const ContextMenuContent = React.forwardRef<
  React.ElementRef<typeof ContextMenuPrimitive.Content>,
  React.ComponentPropsWithoutRef<typeof ContextMenuPrimitive.Content>
>(({ className, onPointerUpCapture, ...props }, forwardedRef) => {
  const releaseSelectsRef = React.useRef(false);
  // The menu opens under the pointer and can be shifted so an item sits
  // beneath it. Radix selects an item on pointer release, so the release of
  // the opening right-click or long press would pick that item. A release
  // only selects once the pointer has travelled since the menu opened.
  const contentRef = React.useCallback(
    (node: HTMLDivElement | null) => {
      assignRef(forwardedRef, node);
      if (!node) return;
      releaseSelectsRef.current = false;
      let travel = 0;
      const document = node.ownerDocument;
      const trackTravel = (event: PointerEvent) => {
        travel += Math.abs(event.movementX) + Math.abs(event.movementY);
        if (travel < RELEASE_SELECT_MIN_TRAVEL_PX) return;
        releaseSelectsRef.current = true;
        document.removeEventListener("pointermove", trackTravel, true);
      };
      document.addEventListener("pointermove", trackTravel, true);
      return () => {
        document.removeEventListener("pointermove", trackTravel, true);
        assignRef(forwardedRef, null);
      };
    },
    [forwardedRef],
  );

  return (
    <ContextMenuPrimitive.Portal>
      <ContextMenuPrimitive.Content
        ref={contentRef}
        className={cn(
          "z-50 max-h-[--radix-context-menu-content-available-height] min-w-[8rem] overflow-y-auto overflow-x-hidden rounded-md border bg-popover p-1 text-popover-foreground shadow-md animate-in fade-in-80 data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 origin-[--radix-context-menu-content-transform-origin]",
          className,
        )}
        onPointerUpCapture={(event) => {
          onPointerUpCapture?.(event);
          // Radix items skip their pointer-up selection when it is prevented;
          // a click that started on an item still selects through `click`.
          if (!releaseSelectsRef.current) event.preventDefault();
        }}
        {...props}
      />
    </ContextMenuPrimitive.Portal>
  );
});
ContextMenuContent.displayName = ContextMenuPrimitive.Content.displayName;

